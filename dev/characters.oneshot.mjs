import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const q = process.argv[2]; const out = process.argv[3];
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 960, height: 600 } });
page.setDefaultTimeout(240000);
const logs = [];
page.on('console', (m) => logs.push(`[${m.type()}] ${m.text()}`));
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`));
const t0 = Date.now();
await page.goto(`http://localhost:5176/dev/characters.html?shot=1&${q}`, { waitUntil: 'load' });
await page.waitForFunction(() => window.__charLab && window.__charLab.ready, null);
await page.evaluate(() => window.__charLab.ready);
await page.waitForFunction(() => window.__charLab.frames() > 0, null);
const stats = await page.evaluate(() => window.__charLab.stats());
await page.screenshot({ path: out });
console.log('secs', (Date.now()-t0)/1000, JSON.stringify(stats.rigs.map(r => [r.kind, r.drawCalls, r.triangles])), 'calls', stats.calls);
console.log(logs.filter(l => !l.includes('[vite]')).slice(0, 15).join('\n'));
await browser.close();
