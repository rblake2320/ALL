/** The shared "sit down and eat" stage (GDD §5: chair preferring tables, else eat standing). */
export function eatStage(duration = 20): StageDef {
  return {
    target: at.seatNearActor(8, true),
    fallback: at.here(),
    duration,
    anim: 'sitEat',
    expression: 'happy',
    carry: 'plate',
    sfxStart: 'eat',
    bubble: 'plate',
    power: false,
  };
}

