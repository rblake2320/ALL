export type HudKey = keyof typeof HUD_EN;

export const HUD_PREFIX = 'hud.';

registerStrings(Object.fromEntries(Object.entries(HUD_EN).map(([k, v]) => [HUD_PREFIX + k, v])));

function toParams(params?: Record<string, unknown>): StringParams | undefined {
  if (!params) return undefined;
  const out: StringParams = {};
  for (const k of Object.keys(params)) {
    const v = params[k];
    out[k] = v === null || v === undefined || typeof v === 'number' || typeof v === 'string' ? v : String(v);
  }
  return out;
}

/** Translate a HUD key (without the `hud.` prefix). Unknown keys come back as the prefixed key — never throws. */
export function ht(key: HudKey | (string & {}), params?: Record<string, unknown>): string {
  return t(HUD_PREFIX + key, toParams(params));
}

/** True when a HUD key exists (for optional per-id strings like `need.<id>.desc`). */
export function hasKey(key: string): boolean {
  return typeof key === 'string' && Object.prototype.hasOwnProperty.call(HUD_EN, key) && hasString(HUD_PREFIX + key);
}
