/**
 * W-151 held props never sit inside their own body. On the REAL runtime + shipped GLBs, for every body with a
 * sculpted held prop (HELD_PROP_RULES) and every played clip, the prop is measured against the rest of the body over
 * the whole clip (tools/clip-audit/heldPropSelf.ts) and the first place that keeps it within 15 mm of the surface is
 * chosen: hand, a stow spot on the body, or put away. The committed table (src/render/characters/heldPropFit.ts) must
 * equal that choice — a new clip, a re-exported body or a new held prop that clips fails here until regenerated:
 *   UPDATE_HELD_PROP_FIT=1 npx vitest run tests/unit/clip-audit/heldPropFit.test.ts
 * The full sweep runs in `npm run clip:gate`; `npm test` always runs the table/rule check and the owner-report case.
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';
import { HELD_PROP_RULES, stowFor } from '../../../src/render/characters/heldProps';
import { HELD_PROP_FIT } from '../../../src/render/characters/heldPropFit';
import type { BodyId } from '../../../src/shared/cast';
import { chooseFit, PROP_SELF_MAX_MM, propSelf } from '../../../tools/clip-audit/heldPropSelf';
import type { AnimState } from '../../../src/shared/appearance';
import { fullGate, published } from './gate';

const ROOT = resolve(__dirname, '../../..');
const BODIES = Object.keys(HELD_PROP_RULES).sort() as BodyId[];
const ident = (k: string): string => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));

describe.skipIf(!published)('held prop fit table (generated from the rigs, W-151)', () => {
  it('every held-prop body has a row, and the rules read their stow from it', () => {
    expect(BODIES.length).toBeGreaterThanOrEqual(3);
    for (const b of BODIES) {
      expect(Object.keys(HELD_PROP_FIT), b).toContain(b);
      expect(Object.fromEntries(stowFor(b)), b).toEqual(HELD_PROP_FIT[b]);
    }
    // a body without a row falls back to the W-120 hands-down stow
    expect(stowFor('nobody').get('crawl' as never)).toBe('back');
    expect(stowFor('__proto__').get('sleep' as never)).toBe('chest');
  });

  // ~60 s of CPU: part of `npm run clip:gate` (CLIP_GATE_FULL=1) and of the regeneration; the owner-report case below always runs
  it.skipIf(!fullGate && !process.env.UPDATE_HELD_PROP_FIT)('chooses a clear place for every body × played clip and matches the committed table', async () => {
    const table: Record<string, Record<string, string>> = {};
    const report: string[] = [];
    for (const body of BODIES) {
      const fit = await chooseFit(body);
      expect(Object.keys(fit).length, body).toBeGreaterThanOrEqual(40);
      table[body] = {};
      for (const [clip, r] of Object.entries(fit)) {
        expect(r.mm, `${body} ${clip} at ${r.spot}`).toBeLessThanOrEqual(PROP_SELF_MAX_MM);
        if (r.spot !== 'hand') table[body][clip] = r.spot;
        if (r.handMm > PROP_SELF_MAX_MM) report.push(`${body} ${clip}: in hand ${r.handMm.toFixed(0)} mm -> ${r.spot} ${r.mm.toFixed(0)} mm`);
      }
      // seated clips always put the prop away (a chair / table / vehicle surrounds the body)
      for (const clip of Object.keys(fit)) if (clip.startsWith('sit')) expect(fit[clip].spot, `${body} ${clip}`).toBe('away');
    }
    if (process.env.UPDATE_HELD_PROP_FIT) {
      const rows = BODIES.map((b) => `  ${JSON.stringify(b)}: { ${Object.entries(table[b]).map(([k, v]) => `${ident(k)}: '${v}'`).join(', ')} },`);
      writeFileSync(resolve(ROOT, 'src/render/characters/heldPropFit.ts'), `/**
 * GENERATED by tests/unit/clip-audit/heldPropFit.test.ts (UPDATE_HELD_PROP_FIT=1) — do not edit by hand.
 * Per body with a sculpted held prop × played clip: where the prop goes while that clip plays ('back' / 'chest' =
 * stowed on the body, 'away' = put away). Clips not listed keep the prop in the hand.
 */
export const HELD_PROP_FIT: Readonly<Record<string, Readonly<Record<string, 'back' | 'chest' | 'away'>>>> = {
${rows.join('\n')}
};
`);
      writeFileSync(resolve(ROOT, 'dev/out/heldPropFit-report.txt'), report.join('\n') + '\n');
    } else expect(table).toEqual(HELD_PROP_FIT);
  }, 600_000);

  it('the owner report (Lid Guard reading / watching TV in the armchair): the lid is gone from the body', async () => {
    for (const anim of ['sitTV', 'sitRead', 'sit', 'idle', 'walk'] as AnimState[]) {
      const r = await propSelf('shield', anim, 'L', 8, 0.5, true);
      expect(r.mm, anim).toBeLessThanOrEqual(PROP_SELF_MAX_MM);
    }
  }, 120_000);
});
