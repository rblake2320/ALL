/**
 * src/render/agents/reachFit.ts is generated from the real rigs (real clips, CPU-skinned): per body × clip, the front
 * profile (per 10 cm height band, the farthest vertex ahead of the root over 6 clip times; 'hug' without the arms),
 * normalised to height scale 1. The renderer's social spacing and work stand-off (src/render/agents/reach.ts) read it.
 * This suite fails when the table drifts from the assets by more than 1.5 cm or misses a clip the audit matrix plays.
 * Regenerate after a character / cast GLB rebuild:
 *   UPDATE_REACH_FIT=1 npx vitest run tests/unit/clip-audit/reachFit.test.ts
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';
import { SCULPTED_BODY_IDS, type BodyId } from '../../../src/shared/cast';
import { LIE_FIT, REACH_BAND, REACH_BANDS, REACH_FIT } from '../../../src/render/agents/reachFit';
import { frontProfile as runtimeProfile, socialPush, socialSpacing, workStandoff, SOCIAL_PUSH_MAX, WORK_STANDOFF_MAX } from '../../../src/render/agents/reach';
import { BAND, BANDS, CORE_PROFILE_CLIPS, LIE_CLIPS, fitClips, frontProfile, lyingLow } from '../../../tools/clip-audit/reach';
import { ROOT } from '../../../tools/clip-audit/assets';

const BODIES: BodyId[] = ['classic', ...SCULPTED_BODY_IDS];

function encode(p: (number | null)[]): string {
  // (z + 1 m) in whole cm, rounded up (conservative), base 36, two chars per band; '..' = empty band
  return p.map((z) => (z === null ? '..' : Math.max(0, Math.min(1295, Math.ceil((z + 1) * 100 - 1e-6))).toString(36).padStart(2, '0'))).join('');
}

describe('reach fit table (generated from the rigs)', () => {
  it('pure rules: spacing sums the overlapping bands, pushes and stand-offs are clamped', () => {
    expect(socialPush(1.2, 0.6)).toBeCloseTo(0.3, 6);
    expect(socialPush(5, 0)).toBe(SOCIAL_PUSH_MAX);
    expect(socialPush(0.8, 1.0)).toBe(0);
    expect(socialPush(null, 0.5)).toBe(0);
    expect(socialSpacing('classic', 'no-such-clip', 1, 'classic', 'talk', 1)).toBeNull();
    expect(workStandoff('classic', 'no-such-clip', 1, 0.9)).toBe(0);
    for (const b of BODIES) {
      const s = socialSpacing(b, 'talk', 1, b, 'talk', 1)!;
      const p = runtimeProfile(b, 'talk')!;
      let mx = -Infinity;
      for (const v of p) if (!Number.isNaN(v)) mx = Math.max(mx, v);
      // never more than twice the farthest reach, never less than the largest single band sum
      expect(s).toBeLessThanOrEqual(2 * mx + 0.021);
      expect(workStandoff(b, 'clean', 1.06, 0.9)).toBeLessThanOrEqual(WORK_STANDOFF_MAX);
    }
  });

  it('matches the rigs for every body × fit clip', async () => {
    expect(REACH_BAND).toBe(BAND);
    expect(REACH_BANDS).toBe(BANDS);
    const clips = fitClips();
    expect(clips.length).toBeGreaterThan(15);
    const table: Record<string, Record<string, string>> = {};
    const lie: Record<string, Record<string, number>> = {};
    for (const body of BODIES) {
      const row: Record<string, string> = {};
      for (const clip of clips) row[clip] = encode(await frontProfile({ body, height: 0.5 }, clip, 6, CORE_PROFILE_CLIPS.has(clip)));
      table[body] = row;
      const lr: Record<string, number> = {};
      for (const clip of LIE_CLIPS) lr[clip] = Math.round((await lyingLow({ body, height: 0.5 }, clip)) * 1000) / 1000;
      lie[body] = lr;
    }
    if (process.env.UPDATE_REACH_FIT) {
      const rows = Object.entries(table).map(([id, row]) => `  ${JSON.stringify(id)}: {\n${Object.entries(row).map(([c, v]) => `    ${c}: '${v}',`).join('\n')}\n  },`).join('\n');
      writeFileSync(resolve(ROOT, 'src/render/agents/reachFit.ts'), `/**
 * GENERATED by tests/unit/clip-audit/reachFit.test.ts (UPDATE_REACH_FIT=1) — do not edit by hand.
 * Front profile per body × clip at height scale 1: for each ${BAND * 100} cm height band from the floor (${BANDS} bands), the
 * farthest body vertex ahead of the rig root over the clip (6 samples; ${[...CORE_PROFILE_CLIPS].join(', ')} without the arms).
 * Encoding: two base-36 chars per band = (z + 1 m) in whole cm rounded up; '..' = no vertex in that band.
 * Read by reach.ts (social spacing, work stand-off).
 */
export const REACH_BAND = ${BAND};
export const REACH_BANDS = ${BANDS};

export const REACH_FIT: Readonly<Record<string, Readonly<Record<string, string>>>> = {
${rows}
};

/**
 * Per body × lying clip (${LIE_CLIPS.join(', ')}), mean over the clip: the lowest back vertex relative to the rig root
 * (m, height scale 1; negative = the back sinks below the root): lowest spine / chest vertex. Read by reach.ts lieLift.
 */
export const LIE_FIT: Readonly<Record<string, Readonly<Record<string, number>>>> = {
${Object.entries(lie).map(([id, r]) => `  ${JSON.stringify(id)}: { ${Object.entries(r).map(([c, v]) => `${c}: ${v}`).join(', ')} },`).join('\n')}
};
`);
      return;
    }
    const bad: string[] = [];
    for (const [id, row] of Object.entries(table)) {
      for (const [clip, enc] of Object.entries(row)) {
        const got = REACH_FIT[id]?.[clip];
        if (!got) {
          bad.push(`${id} ${clip} missing`);
          continue;
        }
        for (let i = 0; i < BANDS; i++) {
          const a = got.slice(i * 2, i * 2 + 2);
          const b = enc.slice(i * 2, i * 2 + 2);
          if ((a === '..') !== (b === '..')) {
            // a band at the edge of the body can flicker in / out between asset builds: only fronts matter
            continue;
          }
          if (a !== '..' && Math.abs(parseInt(a, 36) - parseInt(b, 36)) > 1.5) bad.push(`${id} ${clip} band ${i}: table ${a} rigs ${b}`);
        }
      }
    }
    for (const [id, r] of Object.entries(lie)) {
      for (const [clip, v] of Object.entries(r)) {
        const got = LIE_FIT[id]?.[clip];
        if (got === undefined || Math.abs(got - v) > 0.01) bad.push(`${id} ${clip} lie low: table ${got} rigs ${v}`);
      }
    }
    expect(bad, `reachFit.ts is stale - regenerate (UPDATE_REACH_FIT=1):\n${bad.slice(0, 20).join('\n')}`).toEqual([]);
  }, 300000);
});
