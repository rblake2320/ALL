/**
 * src/render/agents/seatFit.ts is generated from the real rigs: per body × sit* clip (averaged over the clip) the
 * lumbar back (rearmost trunk vertex at SEAT_HEIGHT + SEAT_LUMBAR) and the seat contact (mean z of the lowest hip
 * vertices). This suite fails when the
 * table drifts from the assets by more than 1 cm. Regenerate: UPDATE_SEAT_FIT=1 npx vitest run tests/unit/seating/seatFit.test.ts
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';
import { SEAT_LUMBAR } from '../../../src/shared/seating';
import { SEAT_FIT, SEAT_FIT_DEFAULT } from '../../../src/render/agents/seatFit';
import { LUMBAR_ABOVE_SEAT, ROOT, SIT_CLIPS, SIT_TIMES, allSitters, hipContactZ, lumbarBack } from './seatRig';

describe('seat fit table (generated from the rigs)', () => {
  it('measures the lumbar back of every body × sit clip and matches the committed table', async () => {
    expect(LUMBAR_ABOVE_SEAT).toBe(SEAT_LUMBAR);
    const table: Record<string, Record<string, [number, number]>> = {};
    for (const s of await allSitters()) {
      const row: Record<string, [number, number]> = {};
      const mean = (a: number[]) => Math.round((a.reduce((x, y) => x + y, 0) / a.length) * 1000) / 1000;
      for (const clip of SIT_CLIPS) {
        const poses = SIT_TIMES.map((t) => s.pose(clip, t));
        const zs = poses.map(lumbarBack).filter(Number.isFinite);
        expect(zs.length, `${s.id} ${clip}`).toBeGreaterThan(0);
        row[clip] = [mean(zs), mean(poses.map(hipContactZ))];
      }
      table[s.id] = row;
    }
    if (process.env.UPDATE_SEAT_FIT) {
      const body = Object.entries(table).map(([id, row]) => `  ${JSON.stringify(id)}: { ${Object.entries(row).map(([c, v]) => `${c}: [${v[0]}, ${v[1]}]`).join(', ')} },`).join('\n');
      writeFileSync(resolve(ROOT, 'src/render/agents/seatFit.ts'), `/**
 * GENERATED by tests/unit/seating/seatFit.test.ts (UPDATE_SEAT_FIT=1) — do not edit by hand.
 * Per body × sit* clip, averaged over the clip, in rig-root space at height scale 1 (metres, z = the sitter's front):
 *   [0] lumbar back: z of the rearmost trunk vertex at DIM.SEAT_HEIGHT + SEAT_LUMBAR (negative = behind the root);
 *   [1] seat contact: mean z of the lowest hip-mass vertices.
 * Used by seat.ts to rest every body's back on the backrest without sliding its seat contact off the lip.
 */
export const SEAT_FIT: Readonly<Record<string, Readonly<Record<string, readonly [number, number]>>>> = {
${body}
};

/** Fallback (unknown body / clip): the classic zombie's 'sit'. */
export const SEAT_FIT_DEFAULT: readonly [number, number] = [${table.classic.sit[0]}, ${table.classic.sit[1]}];
`);
      return;
    }
    for (const [id, row] of Object.entries(table)) {
      for (const [clip, v] of Object.entries(row)) {
        const got = SEAT_FIT[id]?.[clip];
        expect(got, `${id} ${clip} missing`).toBeTruthy();
        expect(Math.abs(got![0] - v[0]), `${id} ${clip} back`).toBeLessThan(0.01);
        expect(Math.abs(got![1] - v[1]), `${id} ${clip} seat`).toBeLessThan(0.01);
      }
    }
    expect(SEAT_FIT_DEFAULT[0]).toBeCloseTo(table.classic.sit[0], 2);
  });
});
